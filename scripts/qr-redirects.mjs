/**
 * Routes every printed short link into the counting function — dist/_redirects.
 *
 * Runs as the last step of `npm run build`, so the rules ship inside the deploy
 * that contains the function and the pages they lead to.
 *
 * The rules are rewrites (200), not redirects: netlify/functions/qr.mjs records
 * the scan and then issues the 302 itself, which is what makes the count
 * complete — see the comment at the top of that file for why the browser can't
 * be trusted to report a scan. The destination lives in the registry and is
 * resolved at request time, so re-pointing a printed code is still a one-line
 * change.
 *
 * Why _redirects and not netlify.toml: Netlify evaluates the rules from
 * _redirects BEFORE the ones in netlify.toml, and netlify.toml ends with the
 * SPA catch-all `/* → /index.html`. A QR rule written below that catch-all
 * would never be reached; written above it by hand it would have to be kept in
 * sync with the registry by memory. Generating the file that is read first
 * removes both problems.
 *
 * One rule per code rather than relying on the wildcard alone: the wildcard has
 * to reconstruct the code through Netlify's :splat placeholder, and an explicit
 * rule per registered code means the codes that are actually printed don't
 * depend on that substitution behaving.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

import { QR_CODES, validate } from '../src/data/qrCodes.mjs';

const ROOT = resolve(import.meta.dirname, '..');
const FILE = join(ROOT, 'dist', '_redirects');
const FUNCTION = '/.netlify/functions/qr';

const START = '# --- BEGIN qr redirects (generated by scripts/qr-redirects.mjs) ---';
const END = '# --- END qr redirects ---';

validate();

const width = Math.max(...QR_CODES.map((entry) => entry.code.length)) + 1;

// The code travels as a path segment, never as a query parameter: on a rewrite
// Netlify discards the destination's query string and substitutes the incoming
// request's, so `?code=qr1` here would arrive empty — and `/qr1?code=qr3` from a
// visitor would arrive in its place, filing the scan under another card.
const rules = QR_CODES.map(
  (entry) => `/${entry.code.padEnd(width)} ${FUNCTION}/${entry.code}  200`,
);

// Anything matching /qr* that is not in the registry — a decommissioned code, a
// typo, a number someone invented. The function sends them to the homepage
// rather than a 404: whoever is holding that piece of paper is a real visitor,
// and a dead end is a worse outcome than an imprecise report. The scan is still
// recorded, under whatever code was asked for, so the mismatch is visible.
//
// This also means no future page may start with "qr" — it would be swallowed
// here. The stats endpoint lives at /api/qr-stats for exactly that reason.
const fallback = `/qr*${' '.repeat(Math.max(1, width - 2))} ${FUNCTION}/qr:splat  200`;

const block = [
  START,
  '# Printed QR short links → the scan counter. Source of truth:',
  '# src/data/qrCodes.mjs. Edit there, never here.',
  ...rules,
  fallback,
  END,
];

// Preserve anything else the file already carries (today: nothing, but a future
// hand-written rule shouldn't be silently deleted by a build), and replace only
// our own block so repeated builds don't stack duplicates.
let existing = existsSync(FILE) ? readFileSync(FILE, 'utf8') : '';
if (existing.includes(START)) {
  existing = existing.replace(
    new RegExp(`${escapeRegExp(START)}[\\s\\S]*?${escapeRegExp(END)}\\n?`),
    '',
  );
}

// Generated rules go first: rules are matched in file order, so a catch-all
// living further down cannot swallow /qr1.
writeFileSync(FILE, `${block.join('\n')}\n${existing.trim() ? `\n${existing.trim()}\n` : ''}`, 'utf8');

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

console.log('\nQR routing written to dist/_redirects:');
for (const entry of QR_CODES) {
  console.log(`  /${entry.code.padEnd(width)} → counted, then 302 → ${entry.to}`);
}
console.log(`  /qr*${' '.repeat(Math.max(0, width - 3))} → counted, then 302 → / (unregistered code)\n`);
